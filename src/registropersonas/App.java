    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String documento = txtBuscador.getText().trim();

        if (documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe un número de documento para actualizar.");
            return;
        }

        String generoSeleccionado = "";
        if (rbtnMasculino.isSelected()) {
            generoSeleccionado = "Masculino";
        } else if (rbtnFemenino.isSelected()) {
            generoSeleccionado = "Femenino";
        }

        try (Connection cn = Conexion.getConnection(); PreparedStatement ps = cn.prepareStatement("UPDATE usuarios SET nombre = ?, tipo_documento = ?, estado_civil = ?, genero = ?, fecha_nacimiento = ? WHERE numero_documento = ?")) {
            // 3. Asignar los nuevos valores a los signos '?' en orden
            ps.setString(1, txtNombreCompleto.getText().trim());
            ps.setString(2, jComboxDocumento.getSelectedItem().toString());
            ps.setString(3, jComboxEstadoCivil.getSelectedItem().toString());
            ps.setString(4, generoSeleccionado);

            java.util.Date fechaSeleccionada = fechaNacimiento.getDate();

            if (fechaSeleccionada == null) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar una fecha de nacimiento válida.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }

            java.sql.Date fechaSQL = new java.sql.Date(fechaSeleccionada.getTime());
            ps.setDate(5, fechaSQL);

            ps.setInt(6, Integer.parseInt(documento));

            // 4. Ejecutar la actualización
            int filasAfectadas = ps.executeUpdate();

            if (filasAfectadas > 0) {
                JOptionPane.showMessageDialog(this, "¡Datos del usuario actualizados con éxito!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró ningún usuario con ese documento para modificar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

