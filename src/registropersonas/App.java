    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String documento = txtBuscador.getText().trim();

        if (documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe un número de documento para eliminar.");
            return;
        }

        try (Connection cn = Conexion.getConnection(); PreparedStatement ps = cn.prepareStatement("DELETE FROM usuarios WHERE numero_documento = ?")) {
            ps.setInt(1, Integer.parseInt(documento));

            int filas = ps.executeUpdate();
            if (filas > 0) {
                JOptionPane.showMessageDialog(this, "Eliminado correctamente.");
                limpiarCampos();
                listarUsuarios();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró ningun registro.");
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombreCompleto.getText().trim();
        String documento = txtDocumento.getText().trim();

        if (nombre.isEmpty() || documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, escribe los datos completos.");
            return;
        }

        if (jComboxDocumento.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione el tipo de documento.");
            return;
        }

        if (!rbtnMasculino.isSelected() && !rbtnFemenino.isSelected()) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un género.");
            return;
        }

        if (jComboxEstadoCivil.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione el estado civil.");
            return;
        }

        if (fechaNacimiento.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese la fecha de nacimiento.");
            return;
        }

        String generoSeleccionado = "";
        if (rbtnMasculino.isSelected()) {
            generoSeleccionado = "Masculino";
        } else if (rbtnFemenino.isSelected()) {
            generoSeleccionado = "Femenino";
        }

        try (Connection cn = Conexion.getConnection();
                PreparedStatement ps = cn.prepareStatement("INSERT INTO usuarios(nombre, tipo_documento, numero_documento, estado_civil, genero, fecha_nacimiento) VALUES(?,?,?,?,?,?)")) {

            ps.setString(1, nombre);
            ps.setString(2, jComboxDocumento.getSelectedItem().toString());
            ps.setInt(3, Integer.parseInt(documento));
            ps.setString(4, jComboxEstadoCivil.getSelectedItem().toString());
            ps.setString(5, generoSeleccionado);

            java.util.Date fechaSeleccionada = fechaNacimiento.getDate();
            java.sql.Date fechaSQL = new java.sql.Date(fechaSeleccionada.getTime());
            ps.setDate(6, fechaSQL);

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Guardado correctamente.");
            listarUsuarios();
            limpiarCampos();

        } catch (SQLException e) {
            if (e.getErrorCode() == 1062) {
                JOptionPane.showMessageDialog(this, "El número de documento ya se encuentra registrado.");
            } else {
                JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

