    private void listarUsuarios() {
        // 1. Definir los nombres de las columnas que verá el usuario
        String[] columnas = {"Nombre completo", "Tipo Doc.", "Documento", "Est. Civil", "Sexo", "F. Nacimiento"};

        // 2. Crear el modelo de la tabla (y evitar que el usuario pueda editar las celdas directamente)
        DefaultTableModel modelo = new DefaultTableModel(null, columnas) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Ninguna celda será editable con doble clic
            }
        };

        // 3. Consulta SQL para traer todos los registros
        String sql = "SELECT nombre, tipo_documento, numero_documento, estado_civil, genero, fecha_nacimiento FROM usuarios";

        try (Connection cn = Conexion.getConnection(); PreparedStatement ps = cn.prepareStatement(sql); ResultSet rs = ps.executeQuery()) {

            // Objeto array para almacenar temporalmente los datos de cada fila
            Object[] fila = new Object[7];

            // 4. Recorrer los resultados de la base de datos y agregarlos al modelo
            while (rs.next()) {
                fila[0] = rs.getString("nombre");
                fila[1] = rs.getString("tipo_documento");
                fila[2] = rs.getInt("numero_documento");
                fila[3] = rs.getString("estado_civil");
                fila[4] = rs.getString("genero");
                fila[5] = rs.getDate("fecha_nacimiento"); // MySQL Date se muestra automáticamente como AAAA-MM-DD

                modelo.addRow(fila); // Agrega la fila armada al modelo
            }

            // 5. Asignar el modelo estructurado a tu componente JTable
            tablaUsuarios.setModel(modelo);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

